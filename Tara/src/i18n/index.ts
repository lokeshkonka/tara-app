export type LanguageCode = keyof typeof translations;
// Using literal string type for TranslationKey to allow passing dynamic strings safely
export type TranslationKey = string;

export function getTranslation(lang: string, key: string, params?: Record<string, string | number>): string {
  // Fallback to English if language is not supported
  const languageCode = (translations.hasOwnProperty(lang) ? lang : "en") as LanguageCode;
  
  // Need to cast as any to safely check keys that might not exist in type
  const translationsMap = translations[languageCode] as Record<string, string>;
  const englishMap = translations.en as Record<string, string>;
  
  let text = translationsMap[key] || englishMap[key] || key;
  
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  
  return text;
}
